// Writes out/sw.js after `next build`: a service worker that keeps the whole
// site working offline once it has been opened. It lists every file in out/,
// so a fresh build always ships a fresh cache.
//   node scripts/build-sw.mjs   (runs as part of `npm run build`)
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(fileURLToPath(new URL(".", import.meta.url)), "..", "out");
const SKIP = new Set(["sw.js", ".htaccess"]);

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : SKIP.has(name) ? [] : [full];
  });
}

const files = walk(ROOT);
const hash = createHash("sha256");
const urls = files.map((f) => {
  hash.update(f).update(readFileSync(f));
  const path = "/" + relative(ROOT, f).split(sep).join("/");
  // Pages are requested as folders: /case-study/ rather than /case-study/index.html.
  return path.endsWith("/index.html") ? path.slice(0, -"index.html".length) : path;
});
const version = hash.digest("hex").slice(0, 12);

const sw = `/* Saathi offline support — generated by scripts/build-sw.mjs. Do not edit. */
const VERSION = ${JSON.stringify(version)};
const CACHE = "saathi-" + VERSION;
const PRECACHE = ${JSON.stringify(urls)};

// Install: fetch every file of this build. One failure must not sink the rest.
self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) =>
      Promise.allSettled(PRECACHE.map((url) => fetch(url, { cache: "reload" }).then((res) => res.ok && cache.put(url, res)))),
    ),
  );
  self.skipWaiting();
});

// Activate: drop caches from older builds.
self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith("saathi-") && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  );
});

const fromCache = (request) => caches.open(CACHE).then((cache) => cache.match(request, { ignoreSearch: true }));

self.addEventListener("fetch", (event) => {
  const { request } = event;
  const url = new URL(request.url);
  if (request.method !== "GET" || url.origin !== self.location.origin) return;

  // Hashed build assets never change: cache first.
  if (url.pathname.startsWith("/_next/static/")) {
    event.respondWith(fromCache(request).then((hit) => hit || fetch(request)));
    return;
  }

  // Pages and data: the network when it answers quickly, the saved copy when it doesn't.
  event.respondWith(
    (async () => {
      const network = fetch(request).then(async (res) => {
        if (res.ok) (await caches.open(CACHE)).put(url.pathname, res.clone());
        return res;
      });
      const timeout = new Promise((resolve) => setTimeout(resolve, 3500));
      try {
        const res = await Promise.race([network, timeout]);
        if (res) return res;
      } catch {
        /* offline — fall through to the saved copy */
      }
      const hit = await fromCache(request);
      if (hit) return hit;
      try {
        return await network;
      } catch {
        return (await fromCache(new Request("/404.html"))) || Response.error();
      }
    })(),
  );
});
`;

writeFileSync(join(ROOT, "sw.js"), sw);
console.log(`sw.js: ${urls.length} files precached · version ${version}`);
